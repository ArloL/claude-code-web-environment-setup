#!/bin/sh
#
# Regenerate the allowed-domains files that have a machine-readable upstream
# source of truth, then re-render the list in README.md.
#
#     sh network/refresh-sources.sh
#
# Two lists move without anything in this repo changing, and both have bitten
# us: Anthropic adds domains to the default list (making our entries redundant),
# and the Zig project adds community mirrors (making our list incomplete, which
# shows up as a random 503 because mise shuffles the mirrors). Polling the
# upstream lists on a schedule turns both into a pull request instead of a
# debugging session.
#
# .github/workflows/refresh-network-sources.yaml runs this monthly.

set -o errexit
set -o nounset
set -o xtrace

cd "$(dirname "$0")/.." || exit 1

# --- Anthropic's default allowed-domains list -------------------------------
# Documented at https://code.claude.com/docs/en/cloud-environments -- the
# "Default allowed domains" section. Not part of the list we paste into the UI;
# it is what lets build-allowed-domains.py flag entries we no longer need to
# carry, given the "Also include default list of common package managers" box.
claude_docs="$(mktemp)"
trap 'rm -f "${claude_docs}"' EXIT
curl --fail --silent --show-error --location \
    https://code.claude.com/docs/en/cloud-environments.md \
    --output "${claude_docs}"

{
    echo "# Anthropic's default allowed-domains list for Claude Code cloud"
    echo "# environments -- what the \"Also include default list of common package"
    echo "# managers\" checkbox adds on top of our own list."
    echo "#"
    echo "# GENERATED by network/refresh-sources.sh from"
    echo "# https://code.claude.com/docs/en/cloud-environments.md"
    echo "# Do not edit by hand."
    python3 network/extract-claude-defaults.py < "${claude_docs}"
} > network/claude-defaults.txt

# --- Zig community mirrors --------------------------------------------------
# Every host in ziglang.org/download/community-mirrors.txt is a candidate on any
# given install, because mise shuffles the list. Taking the hostnames out of that
# file is not sufficient -- a mirror may redirect to a host that appears in no
# upstream list -- so resolve-zig-mirrors.py probes each one. It writes to a
# temporary file first: a failure part-way through must not leave a truncated
# allowlist behind.
#
# Setting MISE_ZIG_USE_COMMUNITY_MIRRORS=false would collapse all of this to
# ziglang.org alone, at the cost of putting the load on the Zig project itself.
zig_mirrors="$(mktemp)"
trap 'rm -f "${claude_docs}" "${zig_mirrors}"' EXIT
python3 network/resolve-zig-mirrors.py > "${zig_mirrors}"
cp "${zig_mirrors}" network/allowed-domains/zig-mirrors.txt

# --- Re-render the list in README.md ---------------------------------------
python3 network/build-allowed-domains.py --update-readme
